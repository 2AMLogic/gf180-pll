"""``vco_bias.sch``'s V-to-I core: the dozen-odd transistors ``bias_resistors.py``
named as issue #293's own remaining scope (``MP1``/``MP2``/``MN1``/``MN2``/
``MSU1``-``MSU3``/``MPR``/``MD1``/``MD2``/``MOFF``/``MVI``/``MSUM``).

WHAT THIS CIRCUIT DOES (read directly off ``design/vco_bias.sch`` /
``design/netlist/vco.spice`` -- see ``devices.py``'s own V-to-I section for
the per-device table)
--------------------------------------------------------------------------
Four cooperating pieces, all summed into one output node (``VBP0``):

* **Constant-gm reference**: ``MP1``/``MN1`` (a diode-connected branch,
  node ``NA``) sets the gate of ``MN2``, whose source is degenerated by
  ``RCG`` (through node ``NC``) against ``MP2``'s own diode-connected drain
  (node ``VBPC``) -- the classic beta-multiplier bias cell.
* **Startup**: ``MSU1`` (gate tied permanently to ``GND_VCO`` -- an
  always-on weak pull-up) and ``MSU2`` (gate driven by ``NA``) form a
  detector on node ``NSU``; ``MSU3`` uses ``NSU`` to kick ``VBPC`` low at
  power-up so the constant-gm loop cannot get stuck at its degenerate
  all-zero-current solution.
* **2*Vgs stacked reference**: ``MPR`` (gate ``VBPC``, i.e. mirrored from
  the constant-gm core) stacks over two diode-connected nfets ``MD1``/
  ``MD2`` (node ``NMD`` between them) to produce a fixed gate bias
  ``VFIX`` for the two branches below.
* **Offset + source-degenerated V-to-I + summing node**: ``MOFF`` (gate
  ``VFIX``, degenerated by ``ROFF`` through node ``NOFF``) sets a fixed
  offset current; ``MVI`` (gate ``VCTRL``, the block's own external
  control-voltage input, degenerated by ``RDEG`` through node ``NVI``) is
  the actual V-to-I converter. Both drains land on ``VBP0``, which
  ``MSUM`` (diode-connected, ``nf=4``) mirrors into a PMOS bias node --
  ``VBP0`` is exactly the net ``mirror.py``'s cascade A already consumes as
  ``devices.CASCADE_A.always_on.gate_net``.

WHY THIS IS ITS OWN BLOCK, NOT MERGED WITH ``bias_resistors.py``
------------------------------------------------------------------
``RCG``/``ROFF``/``RDEG`` (the three ``ppolyf_u_3k`` poly resistors this
core's ``NC``/``NOFF``/``NVI`` nodes connect to) are already drawn, DRC-clean
and standalone, by ``bias_resistors.py``. This module draws every
*transistor* of the V-to-I core as its own standalone, DRC-clean block and
exposes ``NC``/``NOFF``/``NVI`` as Metal1/Metal2 boundary pins **using the
exact same net names** ``bias_resistors.py`` already uses for its own
``top_net`` pins -- so wiring the two blocks together (dropping both into
one shared guard ring, and running one combined DRC pass) is a
well-defined, mechanical follow-up rather than a re-derivation. That
follow-up, plus the identical merge with ``ring.py``/``mirror.py``/
``buffer.py``, has since landed as ``block.py`` -- and it *was* mechanical:
it adds no device geometry at all, only the routes between the pins these
five generators already agreed on, plus one block-level guard ring.
See ``bias_resistors.py``'s module docstring for the same call made for the
resistor trio.

WHY THIS BLOCK USES THE SAME METAL2-MESH ROUTING AS ``mirror.py``
--------------------------------------------------------------------
Unlike ``ring.py``'s block (a simple 5-stage chain) or ``buffer.py``'s
(three independent inverters), this circuit's internal nodes fan out across
more than two devices each, and several (``VBPC``, ``NSU``, ``VFIX``,
``VBP0``) are needed from **both** the NMOS and PMOS rows -- e.g. ``VBPC``
is ``MP1``'s gate, ``MP2``'s diode-connected drain/gate, ``MPR``'s gate
(all PMOS row) *and* ``MSU3``'s drain (NMOS row). That is exactly the
"mesh, not a chain" topology ``mirror.py``'s module docstring names as the
reason for Metal2 tracks -- so this module reuses that exact construction
(one Metal1 escape per device terminal, up/down to a Metal2 track in the
channel between the two rows; nets needed from both rows get a "lo" track
reachable only from the NMOS row and a "hi" track reachable only from the
PMOS row, tied together by one Metal1 link column, per ``mirror.py``'s own
"THE CHANNEL IS SPLIT INTO TWO TRACK GROUPS" rationale) rather than
re-deriving a second routing scheme. Every device here is an ordinary
single- or multi-finger MOSFET (no common-centroid array), so the
cascade-specific code in ``mirror.py`` (``draw_cc_array``,
``check_common_centroid``) has no counterpart here.

``MSUM`` is the one multi-finger device (``nf=4``); its four fingers are
drawn side by side and bused together on all three terminals (source,
drain, gate) as one merged Metal1 rectangle each -- simpler than
``mirror.py``'s interdigitated bus (no second leg to keep separate, so no
second gate bus is needed).

THE ONE DEVICE THAT IS NOT MESH-ROUTED: ``MSU1``'s GATE
------------------------------------------------------------
``MSU1`` (in the PMOS row) has its gate tied permanently to ``GND_VCO`` --
an always-on weak pull-up, not a mesh net. Routing it through the general
escape/track mechanism would need a "GND_VCO" track plus a separate anchor
wire all the way down to the substrate ring, crossing the entire NMOS row's
height. Instead, ``MSU1`` is placed **last** (rightmost) in the PMOS row
(``devices.VTOI_PMOS_ROW``'s own ordering, and its own comment), so nothing
else in either row sits further right, and its gate pad is tied with a
single horizontal Metal1 run at the gate's own height straight out to the
guard ring's right-hand band (which the same ``GND_VCO`` net already ties
via ``primitives.guard_ring()``) -- entirely within the PMOS row's own
vertical span, never descending into the channel/NMOS-row region at all.
``devices.py``'s own ``_net_rows()``-equivalent here excludes any
gate/S/D terminal literally equal to ``VDD_VCO``/``GND_VCO`` from mesh
routing (see ``_net_rows()`` below), so this device's gate is the only one
that needs the bespoke wire rather than an ordinary rail_stub -- every
other rail-tied terminal in this block is a source/drain pad, which
``rail_stub()`` already handles.

EVERY PMOS-ROW BOTTOM/GATE ESCAPE HOPS OVER ``tap_band_bottom`` (issue #376)
------------------------------------------------------------------------
The PMOS row is *top*-aligned (``_y_bottom()``'s own pfet convention: every
item's own top edge is ``plan.pmos_top``, so a shorter device's own body
sits higher, not lower) specifically so ``MSU1``'s own ``l=20 um`` channel
-- the tallest thing in the row -- can reach all the way down to
``plan.pmos_bottom`` without every *other* device's own pads needing to
move. But every PMOS-row device's own **bottom** (source) pad still has to
reach the inter-row channel below, and ``plan.tap_band_bottom`` (the
``VDD_VCO`` n-well tap band ``build()`` draws along the row's own bottom
edge, spanning the *entire* row width) sits directly in that path for
every one of them, not just ``MSU1``. A plain ``escape()`` column -- a
single Metal1 wire straight down to the channel, what every other
mesh-routed net in this block uses -- runs directly through that band's own
drawn Metal1, merging the escaping net into ``VDD_VCO``. Root-caused by
direct ``klayout.db`` connectivity probing (not assumed): all five of this
row's own bottom nets (``NA``, ``VBPC``, ``VFIX``, ``VBP0``, ``NSU``) showed
this identical merge before ``_pmos_row_escape()`` existed --
``VBP0`` is the only one of the five with a boundary pin, which is why it
was the only one issue #376 could see from ``vco_block``'s own assembled
LVS. ``_pmos_row_escape()`` (used for every PMOS-row bottom *and* gate pad
instead of the general ``escape()``) hops onto Metal2 for exactly the
crossing -- Metal2 has no spacing relationship with Metal1 at all, the same
fact ``block.py``'s own top-level routing and ``ring.py``'s #371 fix both
already lean on -- then returns to Metal1 for the rest of the descent. See
``layout/evidence/vco-layout/PROOF-376-vbp0-fix.md`` -- including that
record's own disclosure that this fix, by resolving the ``VBP0``/``VDD_VCO``
short, exposes a distinct, separately-scoped ``NC``/``NOFF``/``NVI`` circuit-pin
artifact in the assembled ``vco_block`` LVS, filed as issue #378.

Standalone-DRC scope: like every other VCO sub-block, this one draws its
own dedicated guard ring (outer substrate ``p`` ring tied ``GND_VCO``, an
n-well tap band tied ``VDD_VCO``) so it is provable on its own.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from . import devices as dev
from . import primitives as prim
from ._escape_builder import EscapeBuilderMixin

TOP_CELL = "vco_vtoi_core"

VDD_NET = "VDD_VCO"
GND_NET = "GND_VCO"

# --- generator geometry (um) -- same values as mirror.py's own mesh block,
# for the same reasons (see that module's own constant docs). ---
SD_OVERHANG_UM = 1.5
DEVICE_GAP_UM = 3.4
FINGER_GAP_UM = 3.0  # between MSUM's own fingers
JOG_ESCAPE_UM = 1.1
ESCAPE_WIRE_W_UM = 0.44
TRACK_PITCH_UM = 0.8
CHANNEL_MARGIN_UM = 1.0
LINK_PITCH_UM = 1.0
LINK_MARGIN_UM = 3.0

TAP_GAP_UM = 0.6
TAP_BAND_WIDTH_UM = 0.6
RING_WIDTH_UM = 1.2
OUTER_MARGIN_LEFT_UM = 3.0
OUTER_MARGIN_RIGHT_UM = 3.0
OUTER_MARGIN_BELOW_UM = 2.5
OUTER_MARGIN_ABOVE_UM = 2.5

# Inter-device net order (excludes VDD_VCO/GND_VCO rails and MSU1's own
# GND_VCO-tied gate, which is routed separately -- see module docstring).
NET_ORDER = (
    "VCTRL",
    "NC",
    "NOFF",
    "NVI",
    "NA",
    "NMD",
    "NSU",
    "VFIX",
    "VBPC",
    "VBP0",
)

NMOS_ROW = tuple(f.name for f in dev.VTOI_NMOS_ROW)
PMOS_ROW = tuple(f.name for f in dev.VTOI_PMOS_ROW)


def _device_index() -> dict[str, dev.Fet]:
    return {f.name: f for f in dev.VTOI_ALL_FETS}


DEVICES = _device_index()


def device_height_um(l_um: float) -> float:
    return 2 * SD_OVERHANG_UM + l_um


def finger_footprint_w_um(fet: dev.Fet) -> float:
    """One finger's own drawn x-footprint, after MSU1's dog-bone widening.

    ``MSU1`` (``w=0.22 um``) is narrower than ``primitives.MIN_SD_CONTACT_
    WIDTH_UM`` (0.42 um) -- too narrow to drop a legal S/D contact into
    without ``primitives.mosfet()``'s ``min_sd_width_um`` dog-bone (see that
    parameter's own docstring). Every other device in this block is already
    wider than the floor, so this is a no-op for them.
    """
    return max(fet.finger_w_um, prim.MIN_SD_CONTACT_WIDTH_UM)


def item_width_um(fet: dev.Fet) -> float:
    """Pure-Python: the total x-footprint of ``fet`` (all fingers + gaps)."""
    n = fet.fingers
    fw = finger_footprint_w_um(fet)
    if n <= 1:
        return fw
    return n * fw + (n - 1) * FINGER_GAP_UM


