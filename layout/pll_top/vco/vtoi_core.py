class _Builder(EscapeBuilderMixin):
    def __init__(self, canvas: prim.Canvas | None = None) -> None:
        self.plan = plan()
        self.canvas = prim.Canvas(TOP_CELL) if canvas is None else canvas
        self.net_x: dict[tuple[str, int, str], list[float]] = {}
        self.escape_wire_w_um = ESCAPE_WIRE_W_UM

    # -- escape()/jog_escape()/rail_stub()/_y_bottom() are inherited from
    # EscapeBuilderMixin -- identical construction to mirror.py's own (see
    # that module's docstring for the two-track-group rationale), factored
    # out in _escape_builder.py. This block passes ``self.plan`` itself as
    # the ``bank`` argument those methods take: it has exactly one implicit
    # bank, and ``Plan`` above carries the same index/pmos_top/nmos_bottom/
    # track_y() a one-bank stand-in would need. -----------------------------

    # -- devices -------------------------------------------------------------
    @staticmethod
    def _bus(pads: list[tuple]) -> tuple:
        x0 = min(p[0] for p in pads)
        x1 = max(p[2] for p in pads)
        return (x0, pads[0][1], x1, pads[0][3])

    def _pmos_row_escape(self, net: str, x: float, pad_edge_y: float) -> None:
        """Like ``escape()``, for a PMOS-row pad (bottom *or* gate) -- but
        hops onto Metal2 across ``plan.tap_band_bottom`` (issue #376).

        Every PMOS-row device here is *top*-aligned to ``plan.pmos_top``
        (``_y_bottom()``'s own pfet convention), so a device's own bottom
        and gate pads always sit *above* ``tap_band_bottom`` -- the
        ``VDD_VCO`` n-well tap band ``build()`` draws along the row's own
        bottom edge, spanning the row's full width (``plan.tap_band_bottom
        [0]`` to ``[2]`` == every PMOS item's own x-range). A plain
        ``escape()`` column descending from either pad straight down to the
        inter-row channel -- what every other mesh-routed net in this block
        uses -- would run its own Metal1 directly through the tap band's own
        drawn Metal1 (``primitives.tap_strip()``: comp + contact + a Metal1
        pad), merging whatever net escapes there into ``VDD_VCO``.
        Root-caused by direct ``klayout.db`` connectivity probing, not
        assumed: every one of this row's own bottom *and* gate escapes
        (``NA``, ``VBPC`` -- reached from three different devices' own gate
        and/or bottom pads -- ``VFIX``, ``VBP0``, ``NSU``) showed this
        identical merge before this method existed -- ``VBP0`` is the only
        one of them with a boundary pin, which is why it was the only one
        issue #376 could see from ``vco_block``'s own assembled LVS. See
        ``layout/evidence/vco-layout/PROOF-376-vbp0-fix.md``.

        Metal2 has no spacing relationship with Metal1 (the same fact
        ``block.py``'s own top-level routing and ``ring.py``'s #371 fix both
        already lean on), so this runs Metal1 from the pad down to just
        above the tap band's own drawn edge, hops onto Metal2 for exactly
        the crossing, then returns to Metal1 (via the ordinary ``escape()``)
        for the rest of the descent to the net's own channel track --
        unconditionally, for *every* PMOS-row escape regardless of whether
        its own x happens to fall inside the tap band's drawn extent, the
        same "no obstruction inventory needed" shape ``ring.py``'s own
        wraparound-riser fix used for an analogous same-layer crossing.
        """
        tb = self.plan.tap_band_bottom
        # tap_strip() itself grows the tap band's own drawn Metal1 pad
        # METAL1_PAD_MARGIN_UM past the comp box ``tap_band_bottom`` gives,
        # and via1_stack()'s own landing pad (half-width VIA1_SIZE_UM/2 +
        # VIA1_METAL_ENCLOSE_UM) is what actually has to clear that edge by
        # DRC_METAL1_MIN_SPACE_UM (M1.2a) -- not the hop point itself.
        via_half_pad = prim.VIA1_SIZE_UM / 2.0 + prim.VIA1_METAL_ENCLOSE_UM
        clear = prim.METAL1_PAD_MARGIN_UM + dev.DRC_METAL1_MIN_SPACE_UM + via_half_pad
        hop_hi = tb[3] + clear  # just above the tap band's own drawn Metal1
        hop_lo = tb[1] - clear  # just below it
        if not pad_edge_y > hop_hi:
            raise ValueError(
                f"{net!r}'s own pad ({pad_edge_y}) does not clear the tap band's "
                f"own hop zone (>{hop_hi}) -- _pmos_row_escape()'s own "
                "top-aligned-row assumption no longer holds"
            )
        half = self.escape_wire_w_um / 2.0
        prim.v_wire(self.canvas, x, pad_edge_y, hop_hi, width=self.escape_wire_w_um)
        prim.via1_stack(self.canvas, x, hop_hi)
        self.canvas.rect("metal2", x - half, hop_lo, x + half, hop_hi)
        prim.via1_stack(self.canvas, x, hop_lo)
        self.plan.reserve(net, x - half, hop_hi, x + half, pad_edge_y)
        # The rest of the descent (hop_lo -> the net's own channel track) is
        # an ordinary Metal1 escape() -- same reserve()/net_x bookkeeping
        # every other mesh-routed net gets.
        self.escape(net, x, hop_lo, "pfet", self.plan)

    def draw_fet(self, item: Item, row: str) -> None:
        fet = item.fet
        y_bottom = self._y_bottom(row, device_height_um(fet.l_um), self.plan)
        n = fet.fingers
        fw = fet.finger_w_um

        footprint_w = finger_footprint_w_um(fet)
        finger_ports = []
        x = item.x0
        for _ in range(n):
            finger_ports.append(
                prim.mosfet(
                    self.canvas,
                    fet,
                    x,
                    y_bottom,
                    w_um=fw,
                    sd_overhang=SD_OVERHANG_UM,
                    min_sd_width_um=prim.MIN_SD_CONTACT_WIDTH_UM,
                )
            )
            x += footprint_w + FINGER_GAP_UM

        if n == 1:
            p0 = finger_ports[0]
            bottom_pad, top_pad, gate_pad = p0.bottom_pad, p0.top_pad, p0.gate_pad
            gate_tab_x_center = p0.gate_tab_x_center
        else:
            bottom_pad = self._bus([p.bottom_pad for p in finger_ports])
            top_pad = self._bus([p.top_pad for p in finger_ports])
            gate_pad = self._bus([p.gate_pad for p in finger_ports])
            self.canvas.rect("metal1", *bottom_pad)
            self.canvas.rect("metal1", *top_pad)
            self.canvas.rect("metal1", *gate_pad)
            gate_tab_x_center = (gate_pad[0] + gate_pad[2]) / 2.0

        x_pad_c = (bottom_pad[0] + bottom_pad[2]) / 2.0
        x_jog = item.x0 + item.width + JOG_ESCAPE_UM

        if row == "pfet":
            if fet.top_net == VDD_NET:
                self.rail_stub(VDD_NET, x_pad_c, top_pad[3], self.plan.tap_band[1])
            else:
                self.jog_escape(fet.top_net, top_pad, x_jog, row, self.plan)
            self._pmos_row_escape(fet.bottom_net, x_pad_c, bottom_pad[1])
            if fet.gate_net == GND_NET:
                # MSU1: tie its gate directly to the guard ring's right band
                # (module docstring) -- drawn once, after every item is
                # placed, in build() (needs self.plan.outer[2]).
                self._msu1_gate_pad = gate_pad
            else:
                self._pmos_row_escape(fet.gate_net, gate_tab_x_center, gate_pad[1])
        else:
            if fet.bottom_net == GND_NET:
                ring_top = self.plan.outer[1] + RING_WIDTH_UM + prim.METAL1_PAD_MARGIN_UM
                self.rail_stub(GND_NET, x_pad_c, bottom_pad[1], ring_top)
            else:
                self.jog_escape(fet.bottom_net, bottom_pad, x_jog, row, self.plan)
            self.escape(fet.top_net, x_pad_c, top_pad[3], row, self.plan)
            self.escape(fet.gate_net, gate_tab_x_center, gate_pad[3], row, self.plan)

    # -- assembly ------------------------------------------------------------
    def build(self) -> VtoiCoreResult:
        p = self.plan
        self._msu1_gate_pad: tuple | None = None
        for item in p.pmos:
            self.draw_fet(item, "pfet")
        for item in p.nmos:
            self.draw_fet(item, "nfet")

        pad = ESCAPE_WIRE_W_UM / 2.0
        track_x1: dict[str, float] = {}
        for net in NET_ORDER:
            for row in ("nfet", "pfet"):
                xs = self.net_x.get((net, p.index, row))
                if not xs:
                    continue
                x_link = p.link_x.get(net)
                x1 = max(xs + ([x_link] if x_link is not None else []))
                prim.m2_wire(self.canvas, min(xs) - pad, x1 + pad, p.track_y(net, row))
                track_x1[net] = max(track_x1.get(net, x1), x1)

        for net, x in p.link_x.items():
            y0, y1 = p.track_lo[net], p.track_hi[net]
            self.plan.reserve(net, x - pad, y0, x + pad, y1)
            prim.v_wire(self.canvas, x, y0, y1, width=ESCAPE_WIRE_W_UM)
            prim.via1_stack(self.canvas, x, y0)
            prim.via1_stack(self.canvas, x, y1)

        # --- MSU1's gate: one horizontal Metal1 run at the gate pad's own
        # height, straight into the guard ring's right band (see module
        # docstring's "THE ONE DEVICE THAT IS NOT MESH-ROUTED" section). ---
        if self._msu1_gate_pad is not None:
            gp = self._msu1_gate_pad
            y_c = (gp[1] + gp[3]) / 2.0
            width = gp[3] - gp[1]
            ring_inner_x = p.outer[2] - RING_WIDTH_UM
            self.plan.reserve("MSU1_GATE_GND_TIE", gp[0], gp[1], ring_inner_x, gp[3])
            prim.h_wire(self.canvas, gp[0], ring_inner_x + 0.5, y_c, width=width)

        # --- block boundary pins ---
        def _leftmost(net: str) -> tuple[float, float]:
            for row in ("nfet", "pfet"):
                xs = self.net_x.get((net, p.index, row))
                if xs:
                    return (min(xs), p.track_y(net, row))
            raise KeyError(net)

        single_row_pins = (dev.VTOI_IN_NET,) + dev.VTOI_RESISTOR_NETS
        for net in single_row_pins:
            x, y = _leftmost(net)
            self.canvas.pin(net, x - pad - 0.6, y - pad, x - pad, y + pad, layer="metal2_label")
            prim.m2_wire(self.canvas, x - pad - 0.6, x, y)

        y = p.track_hi[dev.VTOI_OUT_NET]
        x = track_x1[dev.VTOI_OUT_NET] + pad
        self.canvas.pin(dev.VTOI_OUT_NET, x, y - pad, x + 0.6, y + pad, layer="metal2_label")
        prim.m2_wire(self.canvas, x - pad, x + 0.6, y)

        # --- n-well, its VDD_VCO tap bands (top AND bottom -- see plan()'s
        # own note on why MSU1's L=20 um channel needs both), and the outer
        # GND_VCO guard ring. Both bands make ohmic contact to the same
        # continuous n-well body, so they are the same electrical net
        # without any extra Metal1 jumper between them. ---
        self.canvas.rect("nwell", *p.nwell)
        prim.tap_strip(self.canvas, "n", *p.tap_band, VDD_NET)
        prim.tap_strip(self.canvas, "n", *p.tap_band_bottom, VDD_NET)
        prim.guard_ring(self.canvas, "p", *p.outer, RING_WIDTH_UM, GND_NET)

        return VtoiCoreResult(canvas=self.canvas, plan=p, footprint=p.outer, net_x=self.net_x)


def build(outdir: Path | None = None, canvas: prim.Canvas | None = None) -> VtoiCoreResult:
    """``canvas`` draws into a caller-supplied canvas -- see ``ring.build()``."""
    result = _Builder(canvas).build()
    if outdir is not None:
        outdir = Path(outdir)
        outdir.mkdir(parents=True, exist_ok=True)
        result.canvas.write_gds(outdir / f"{TOP_CELL}.gds")
    return result


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--outdir",
        default=str(Path(__file__).resolve().parents[2] / "evidence" / "vco-layout" / "work"),
    )
    args = parser.parse_args()
    result = build(Path(args.outdir))
    x0, y0, x1, y1 = result.footprint
    print(f"wrote {args.outdir}/{TOP_CELL}.gds")
    print(f"footprint: {x1 - x0:.3f} x {y1 - y0:.3f} um  ({(x1 - x0) * (y1 - y0):.1f} um^2)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
