"""Layout-evidence extractors shared by the layout generator and checker.

``audit_rows`` reads the geometry table of
``layout/evidence/area-audit/area-audit.md``; ``klayout_pin`` reads
``KNOWN_GOOD_KLAYOUT_VERSION`` out of ``layout/harness/env.py``. Both were
carried twice -- once in ``layout/lib/gen_layout_status_table.py``, which
*writes* the status table, and once in a ``layout/lib/check-layout-status-
claims.sh`` heredoc, which *grades* prose claims against the same two files.

That pairing is why the duplication mattered more than its line count. The
generator and the checker read the same evidence for opposite purposes, so a
format change applied to one copy of a pattern and not the other does not
fail loudly: the checker keeps grading against whatever its own copy still
matches, and the result is a silent pass. The bodies live here once.

Neither helper opens a file. Both callers already resolve their own paths and
already disagree, correctly, about what an unreadable file means -- the
checker fails the run, the generator degrades to ``"n/a"`` / ``"unknown"`` --
so each keeps its own ``open`` and its own error text, and what is shared is
the parse.
"""

import re

#: A row of area-audit.md's *geometry* table: block name, ``W x H``, bbox.
#:
#: The later tables in the same file open with the same ``| `block` |`` cell
#: but carry a plain figure in the second column rather than a ``W x H``
#: pair, so requiring that pair selects the geometry table without having to
#: count tables. ``×`` is accepted beside ``x`` because the audit is
#: regenerated by ``python3 layout/run_pv.py area`` and the rendered table
#: has used both.
AUDIT_ROW = re.compile(
    r"^\|\s*`([A-Za-z0-9_]+)`\s*\|\s*([0-9]+(?:\.[0-9]+)?)\s*[xX×]\s*"
    r"([0-9]+(?:\.[0-9]+)?)\s*\|\s*([0-9,]+)\s*\|"
)

#: ``KNOWN_GOOD_KLAYOUT_VERSION = "KLayout 0.28.16"`` in layout/harness/env.py.
#: Anchored per line so an assignment inside a docstring or a comment further
#: in cannot be read as the module's own pin.
KLAYOUT_PIN = re.compile(r'^KNOWN_GOOD_KLAYOUT_VERSION\s*=\s*"([^"]+)"', re.M)


def audit_rows(text):
    """``{top cell: (width, height, bbox_um2)}`` from an area-audit document.

    Width and height are returned **as written** -- the strings
    ``"226.69"``, ``"184.48"`` -- and only the bbox is converted, to ``int``
    with its thousands separators stripped. The two callers want different
    types and the as-written string is the one that can still become either:
    the generator renders the pair straight into the committed table, where
    ``float("20.00")`` would print ``20.0`` and silently rewrite the table,
    while the checker compares numerically and so converts at its call site.
    Parsing to ``float`` here would make the lossy reading the only one
    available.

    The first row wins where a block name repeats, which is the rule both
    copies applied: the geometry table is one row per block, so a second row
    for a name already seen is a later table's row that happens to match.
    """
    rows = {}
    for line in text.splitlines():
        found = AUDIT_ROW.match(line.strip())
        if found and found.group(1) not in rows:
            rows[found.group(1)] = (
                found.group(2),
                found.group(3),
                int(found.group(4).replace(",", "")),
            )
    return rows


def klayout_pin(text):
    """The ``KNOWN_GOOD_KLAYOUT_VERSION`` string in ``text``, or ``None``.

    ``None`` rather than a stand-in, because the callers must not be made to
    agree about absence: an undeclared pin leaves every committed deck log's
    engine claim gradeable against nothing, which the checker reports as a
    failure, while the generator has a table to render regardless and prints
    ``unknown``. Returning ``None`` and letting each caller decide keeps that
    difference where it is visible, the way ``checklib.files.read_text``
    leaves the caller to act on ``None``.
    """
    found = KLAYOUT_PIN.search(text)
    return found.group(1) if found else None
