"""Generate the #1090 migration requests from the committed campaign inputs.

Extends the #1083 pilot (one ``klt sim`` request per sweep point, point
params + solver options pinned in a circuit body that ``.include``s the
committed DUT and stimulus) to the 190 points of record
``20261114-093804-ad9eef8`` the pilot did not cover:

- ``f200n04``  -- the full 45-point PVT grid at N = 4;
- ``f200n05``..``f200n32``, ``f200n34``..``f200n63`` -- one request per
  divisor at the two stress corners the committed record swept them at
  (SS/125 C/2.97 V and FF/-40 C/3.63 V);
- ``f200n64``  -- the 17 retiming-margin points (15 low-supply + FF/-40 C/
  3.63 V + typical/27 C/3.30 V), split into one request per distinct
  ``tsetup_s`` joined from ``sim/divider-ratio-dff`` so the per-PVT join
  value is pinned in each body and ``setup_margin``/``hold_margin`` are
  request measurements with limits;
- ``f010n04``/``f010n64`` -- the 10 MHz bottom-of-band checks (five
  processes at 125 C/2.97 V plus typical/27 C/3.30 V per divisor).

Inputs are read read-only: ``../../testbench/tb.json`` (the campaign's own
point definitions -- every ``kf``/``ktstep``/``ktstop``/``kn``/SEL/P code
comes from there, never recomputed) and the committed DFF join table
``../../divider-ratio-dff/corners/20261114-080736-f53d562/dff_setup_hold.csv``.
Outputs (``netlists/*.sp``, ``requests/*.request.json``) are deterministic;
re-running this script must leave a clean ``git diff``.

Supply stays a ``corners.params`` row on ``vdd_val`` (every rail in the
stimulus scales from that one parameter, so ``corners.supply_v`` cannot move
it), exactly as the pilot did.  Non-rectangular PVT selections are carved
with top-level ``exclude`` rules; the script asserts the kept unit set of
every request against the selection it names, so a wrong exclude rule fails
generation instead of silently simulating the wrong grid.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CAMPAIGN = HERE.parent.parent          # sim/divider-ratio-chain
TB = CAMPAIGN / "testbench" / "tb.json"
DFF_CSV = (
    CAMPAIGN.parent / "divider-ratio-dff" / "corners"
    / "20261114-080736-f53d562" / "dff_setup_hold.csv"
)
NETLISTS = HERE / "netlists"
REQUESTS = HERE / "requests"

PROCESSES = ["typical", "ff", "ss", "fs", "sf"]
TEMPERATURES = [-40, 27, 125]
SUPPLIES = [2.97, 3.3, 3.63]

#: The f200n64 retiming selection of record 20261114-093804-ad9eef8: every
#: process/temperature at the low supply, plus FF/-40 C/3.63 V and
#: typical/27 C/3.30 V.
N64_EXTRA = [("ff", -40, 3.63), ("typical", 27, 3.3)]

PILOT_POINT = "f200n33"
NSWEEP_DIVISORS = list(range(5, 33)) + list(range(34, 64))

_PDK_REVISION = "open_pdks f6eeac7dad085ffcc829ccfd721f7b4ce39edcf7"

_MEASUREMENTS = [
    ("tfb1", ".meas tran tfb1 when v(fb)='vdd_val/2' rise=1 td='tskip'", "s"),
    ("tfb2", ".meas tran tfb2 when v(fb)='vdd_val/2' rise=2 td='tskip'", "s"),
    ("tdo1", ".meas tran tdo1 when v(divout)='vdd_val/2' rise=1 td='tskip'", "s"),
    ("tdo2", ".meas tran tdo2 when v(divout)='vdd_val/2' rise=2 td='tskip'", "s"),
    ("ffb2", ".meas tran ffb2 when v(fb)='vdd_val/2' fall=2 td='tskip'", "s"),
    ("n_fb", ".meas tran n_fb param='(tfb2-tfb1)/tvco'", "vco_periods"),
    ("ndo", ".meas tran ndo param='(tdo2-tdo1)/tvco'", "vco_periods"),
    ("t_arr", ".meas tran t_arr param='(tdo2-tck0)-tvco*floor((tdo2-tck0)/tvco)'", "s"),
    ("t_rtcq", ".meas tran t_rtcq param='(tfb2-tck0)-tvco*floor((tfb2-tck0)/tvco)'", "s"),
    ("fbpw", ".meas tran fbpw param='ffb2-tfb2'", "s"),
    ("iavg", ".meas tran iavg avg i(vdiv) from='tskip' to='ktstop'", "A"),
]


def load_dff_join() -> dict[tuple[str, int, float], tuple[float, float]]:
    """(process, temp_c, vdd) -> (tsetup_s, thold_s) from the committed table."""
    join: dict[tuple[str, int, float], tuple[float, float]] = {}
    with DFF_CSV.open(encoding="utf-8") as fh:
        lines = [ln for ln in fh if not ln.lstrip().startswith("#")]
        for row in csv.DictReader(lines):
            key = (row["process"], int(float(row["temp_c"])), float(row["vdd_v"]))
            join[key] = (float(row["tsetup_s"]), float(row["thold_s"]))
    return join


def body_text(point_id: str, params: dict[str, str], extra: dict[str, str]) -> str:
    """One circuit body: the pilot's netlist-f200n33.sp composition pattern."""
    ordered = [
        "kf", "ktstep", "ktstop", "kn",
        "ksel0", "ksel1", "ksel2", "ksel3", "ksel4", "ksel5",
        "kp0", "kp1", "kp2", "kp3", "kp4", "kp5",
    ]
    lines = [
        f"* gf180-pll :: divider-ratio-chain :: klt sim circuit body, {point_id} slice",
        "*",
        "* Generated by generate.py from testbench/tb.json -- same composition as the",
        "* #1083 pilot body netlist-f200n33.sp: the committed DUT",
        "* design/netlist/divider_chain.spice composed with the campaign stimulus",
        "* testbench/tb_divider_chain.sp, this sweep point's parameters, and the",
        "* campaign's four solver options. vdd_val stays the supply axis (corners.params",
        "* on the request); the .measure cards that consume these params live in the",
        "* request, not here.",
        f"* ---- {point_id} sweep-point parameters (tb.json sweeps.point.points.{point_id})",
    ]
    lines += [f".param {name}={params[name]}" for name in ordered]
    lines += [f".param {name}={value}" for name, value in extra.items()]
    lines += [
        "* ---- PVT parameter (altered per corner by the request's corners.params)",
        ".param vdd_val=3.3",
        "* ---- solver options (tb.json options, verbatim)",
        ".options reltol=1e-3",
        ".options abstol=1e-10",
        ".options vntol=1e-5",
        ".options chgtol=1e-13",
        "* ---- DUT (composed by netlist.sh from design/divider_chain.sch)",
        ".include ../../../../../design/netlist/divider_chain.spice",
        "* ---- testbench stimulus (sim/divider-ratio-chain/testbench)",
        ".include ../../../testbench/tb_divider_chain.sp",
    ]
    return "\n".join(lines) + "\n"


def measurements(n: int, margins: bool) -> list[dict]:
    """The campaign's eleven cards verbatim, ratio limits per N; the N=64
    requests additionally carry the joined retiming margins as limited,
    spec_row-tagged request measurements."""
    out: list[dict] = []
    for name, spice, unit in _MEASUREMENTS:
        entry: dict = {"name": name, "spice": spice, "unit": unit}
        if name in ("n_fb", "ndo"):
            entry["limits"] = {"min": n - 0.05, "max": n + 0.05}
            entry["spec_row"] = "multiplication-ratio"
        out.append(entry)
    if margins:
        out.append({
            "name": "setup_margin",
            "spice": ".meas tran setup_margin param='tvco-t_arr-tsetup_s'",
            "unit": "s",
            "limits": {"min": 0},
            "spec_row": "retiming-margin",
        })
        out.append({
            "name": "hold_margin",
            "spice": ".meas tran hold_margin param='t_arr-thold_s'",
            "unit": "s",
            "limits": {"min": 0},
            "spec_row": "retiming-margin",
        })
    return out


def request(
    stem: str,
    point_id: str,
    n: int,
    corners: dict,
    exclude: list[dict] | None,
    margins: bool,
    timeout_s: int,
    max_units_per_job: int,
) -> dict:
    params = corners["params"]
    kf, ktstep, ktstop = params_of(point_id)
    req = {
        "netlist": f"../netlists/{stem}.sp",
        "engine": "ngspice",
        "backend": "batch",
        "models": {
            "pdk": "gf180mcuD",
            "lib": "libs.tech/ngspice/sm141064.ngspice",
            "param_file": "libs.tech/ngspice/design.ngspice",
        },
        "corners": corners,
        "analysis": {"kind": "tran", "args": f"{ktstep} {ktstop}"},
        "measurements": measurements(n, margins),
        "options": {
            "timeout_s": timeout_s,
            "stage_model_inputs": True,
            "pdk_revision": _PDK_REVISION,
        },
        "batch": {
            "capacity_wait_s": 600,
            "max_units_per_job": max_units_per_job,
        },
    }
    if exclude:
        req["exclude"] = exclude
    return req


def params_of(point_id: str) -> tuple[str, str, str]:
    raw = TB_DATA["sweeps"]["point"]["points"][point_id]["params"]
    return raw["kf"], raw["ktstep"], raw["ktstop"]


def full_grid(processes: list[str], temps: list[int], vdds: list[float]) -> dict:
    return {
        "process": [
            {"name": p, "sections": [p, "res_typical", "moscap_typical", "mimcap_typical"]}
            for p in processes
        ],
        "temperature_c": temps,
        "params": {"vdd_val": vdds},
    }


def expand(corners: dict, exclude: list[dict] | None) -> list[tuple[str, int, float]]:
    """The kept (process, temp, vdd) set of a request, subset-matched exactly
    like sim_corner_axes._matches_exclude (selector keys AND together)."""
    out = []
    excl = exclude or []
    for process in corners["process"]:
        for temp in corners["temperature_c"]:
            for vdd in corners["params"]["vdd_val"]:
                point = {"process": process["name"], "temperature_c": temp, "params": {"vdd_val": vdd}}
                if not any(
                    all(
                        point.get(key) == value
                        if key != "params"
                        else all(point["params"].get(k) == v for k, v in value.items())
                        for key, value in entry.items()
                    )
                    for entry in excl
                ):
                    out.append((process["name"], temp, vdd))
    return out


def assert_kept(stem: str, kept: list[tuple], expected: list[tuple]) -> None:
    if sorted(kept) != sorted(expected):
        print(f"error: {stem}: kept {len(kept)} corners, expected {len(expected)}", file=sys.stderr)
        for row in sorted(set(kept) ^ set(expected)):
            print(f"  symmetric-difference: {row}", file=sys.stderr)
        raise SystemExit(1)


def write(stem: str, body: str, req: dict) -> None:
    (NETLISTS / f"{stem}.sp").write_text(body, encoding="utf-8")
    (REQUESTS / f"{stem}.request.json").write_text(
        json.dumps(req, indent=2) + "\n", encoding="utf-8"
    )


TB_DATA = json.loads(TB.read_text(encoding="utf-8"))
DFF = load_dff_join()


def main() -> None:
    NETLISTS.mkdir(exist_ok=True)
    REQUESTS.mkdir(exist_ok=True)
    written: list[str] = []

    def emit(stem: str, point_id: str, extra_params: dict, corners: dict,
             exclude: list[dict] | None, n: int, margins: bool,
             timeout_s: int, max_units_per_job: int,
             expected: list[tuple]) -> None:
        raw = TB_DATA["sweeps"]["point"]["points"][point_id]["params"]
        assert_kept(stem, expand(corners, exclude), expected)
        write(
            stem,
            body_text(point_id, raw, extra_params),
            request(stem, point_id, n, corners, exclude, margins, timeout_s, max_units_per_job),
        )
        written.append(stem)

    # --- f200n04: full 45-point PVT grid -----------------------------------
    full = [(p, t, v) for p in PROCESSES for t in TEMPERATURES for v in SUPPLIES]
    emit("f200n04", "f200n04", {}, full_grid(PROCESSES, TEMPERATURES, SUPPLIES),
         None, 4, False, 300, 11, full)

    # --- N sweep: SS/125 C/2.97 V + FF/-40 C/3.63 V per divisor -------------
    stress = [("ss", 125, 2.97), ("ff", -40, 3.63)]
    stress_exclude = [
        {"process": "ss", "temperature_c": -40},
        {"process": "ss", "params": {"vdd_val": 3.63}},
        {"process": "ff", "temperature_c": 125},
        {"process": "ff", "params": {"vdd_val": 2.97}},
    ]
    for n in NSWEEP_DIVISORS:
        point_id = f"f200n{n:02d}"
        emit(point_id, point_id, {},
             full_grid(["ss", "ff"], [125, -40], [2.97, 3.63]),
             stress_exclude, n, False, 300, 2, stress)

    # --- f200n64: 17 retiming points, one request per distinct tsetup -------
    n64 = [(p, t, 2.97) for p in PROCESSES for t in TEMPERATURES] + N64_EXTRA
    for key in n64:
        if key not in DFF:
            raise SystemExit(f"error: DFF join lacks {key}")
    groups: dict[float, list[tuple]] = {}
    for key in n64:
        groups.setdefault(DFF[key][0], []).append(key)
    for index, (tsetup, keys) in enumerate(sorted(groups.items()), start=1):
        tholds = {DFF[k][1] for k in keys}
        if len(tholds) != 1:
            raise SystemExit(f"error: tsetup group {tsetup} mixes thold values {tholds}")
        thold = tholds.pop()
        procs = sorted({k[0] for k in keys})
        temps = sorted({k[1] for k in keys})
        vdds = sorted({k[2] for k in keys})
        exclude = []
        for proc in procs:
            for temp in temps:
                for vdd in vdds:
                    if (proc, temp, vdd) in keys:
                        continue
                    why = {"process": proc}
                    if sum(1 for t_ in temps if (proc, t_, vdd) not in keys) < len(temps):
                        why["temperature_c"] = temp
                    why["params"] = {"vdd_val": vdd}
                    if why not in exclude:
                        exclude.append(why)
        stem = f"f200n64{chr(ord('a') + index - 1)}"
        emit(stem, "f200n64",
             {"tsetup_s": f"{tsetup:.0e}", "thold_s": f"{thold:.0e}"},
             full_grid(procs, temps, vdds), exclude, 64, True, 600, 4, keys)

    # --- 10 MHz bottom-of-band checks ---------------------------------------
    f010 = [(p, 125, 2.97) for p in PROCESSES] + [("typical", 27, 3.3)]
    f010_exclude = [
        {"temperature_c": 27, "params": {"vdd_val": 2.97}},
        {"temperature_c": 125, "params": {"vdd_val": 3.3}},
    ] + [
        {"process": p, "temperature_c": 27, "params": {"vdd_val": 3.3}}
        for p in PROCESSES if p != "typical"
    ]
    for divisor in (4, 64):
        point_id = f"f010n{divisor:02d}"
        emit(point_id, point_id, {},
             full_grid(PROCESSES, [125, 27], [2.97, 3.3]),
             f010_exclude, divisor, False,
             900 if divisor == 4 else 3000,
             2 if divisor == 4 else 1, f010)

    total = sum(
        len(expand(json.loads((REQUESTS / f"{s}.request.json").read_text())["corners"],
                   json.loads((REQUESTS / f"{s}.request.json").read_text()).get("exclude")))
        for s in written
    )
    print(f"wrote {len(written)} requests to {REQUESTS} ({total} corners total)")


if __name__ == "__main__":
    main()
