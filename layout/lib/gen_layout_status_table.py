#!/usr/bin/env python3
"""Generate the layout status table committed in layout/STATUS.md.

Every fact in the table is derived from the committed tree, never typed:

* per sub-block: is there a block GDS plus a recorded DRC deck log, and does a
  recorded LVS log carry the deck's "Netlists match." verdict
  (layout/evidence/<dir>/{drc-clean,lvs-clean}/*.log);
* per sub-block footprint: the first table of
  layout/evidence/area-audit/area-audit.md (regenerated by
  `python3 layout/run_pv.py area` from the committed GDS);
* whether an assembled `pll_top.gds` is committed;
* the KLayout pin: `KNOWN_GOOD_KLAYOUT_VERSION` in layout/harness/env.py.

The block list is read from the BLOCKS array in
layout/lib/check-layout-status-claims.sh so the two cannot disagree.

Usage:
  gen_layout_status_table.py            rewrite the table in layout/STATUS.md
  gen_layout_status_table.py --check    exit 1 (with a diff) if the committed
                                        table differs from the tree
  --root DIR                            repo root (default: this checkout)

CI runs --check, so editing evidence without regenerating the table, or
hand-editing the table, fails the build.
"""
import argparse
import difflib
import glob
import os
import re
import sys

BEGIN = "<!-- layout-status-table:begin"
END = "<!-- layout-status-table:end -->"
BEGIN_LINE = (
    BEGIN
    + " (generated by layout/lib/gen_layout_status_table.py; do not edit by hand) -->"
)
TARGET = "layout/STATUS.md"
AUDIT_ROW = re.compile(
    r"^\|\s*`([A-Za-z0-9_]+)`\s*\|\s*([0-9]+(?:\.[0-9]+)?)\s*[xX×]\s*"
    r"([0-9]+(?:\.[0-9]+)?)\s*\|\s*([0-9,]+)\s*\|"
)


def read_blocks(root):
    path = os.path.join(root, "layout/lib/check-layout-status-claims.sh")
    text = open(path, encoding="utf-8").read()
    m = re.search(r"^BLOCKS=\(\n(.*?)^\)", text, re.M | re.S)
    if not m:
        sys.exit("FAIL: no BLOCKS=( ... ) array in %s" % path)
    blocks = re.findall(r'^\s*"([^"|]+)\|([^"|]+)\|([^"|]+)\|([^"|]+)"', m.group(1), re.M)
    if not blocks:
        sys.exit("FAIL: BLOCKS array in %s parsed to zero entries" % path)
    return blocks


def read_audit(root):
    audit = {}
    path = os.path.join(root, "layout/evidence/area-audit/area-audit.md")
    try:
        lines = open(path, encoding="utf-8").read().splitlines()
    except OSError:
        return audit
    for line in lines:
        m = AUDIT_ROW.match(line.strip())
        if m and m.group(1) not in audit:
            audit[m.group(1)] = (m.group(2), m.group(3), int(m.group(4).replace(",", "")))
    return audit


def read_pin(root):
    path = os.path.join(root, "layout/harness/env.py")
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return "unknown"
    m = re.search(r'^KNOWN_GOOD_KLAYOUT_VERSION\s*=\s*"([^"]+)"', text, re.M)
    return m.group(1) if m else "unknown"


def render(root):
    ev = os.path.join(root, "layout/evidence")
    audit = read_audit(root)
    rows, drawn, lvs_n = [], 0, 0
    for label, d, gds, top in read_blocks(root):
        has_gds = os.path.isfile(os.path.join(ev, d, gds))
        drc_logs = glob.glob(os.path.join(ev, d, "drc-clean", "*.log"))
        lvs_logs = glob.glob(os.path.join(ev, d, "lvs-clean", "*.log"))
        has_drc = bool(drc_logs)
        has_lvs = False
        for log in lvs_logs:
            with open(log, encoding="utf-8", errors="replace") as fh:
                if "Netlists match." in fh.read():
                    has_lvs = True
                    break
        is_drawn = has_gds and has_drc
        drawn += is_drawn
        lvs_n += has_lvs
        if top in audit:
            w, h, bbox = audit[top]
            foot, mm2 = "%s × %s" % (w, h), "%.4f" % (bbox / 1e6)
        else:
            foot, mm2 = "n/a", "n/a"
        rows.append(
            "| %s | `%s` | %s | %s | %s | %s |"
            % (label, top, "yes" if is_drawn else "no", "yes" if has_lvs else "no", foot, mm2)
        )
    top_yes = bool(glob.glob(os.path.join(ev, "*", "pll_top.gds")))
    n = len(rows)
    out = [
        BEGIN_LINE,
        "| Sub-block | Top cell | Block GDS + DRC-clean deck log | LVS `Netlists match.` | Footprint (µm) | bbox (mm²) |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "- Drawn and DRC-clean: **%d of %d** sub-blocks. LVS-matched: **%d of %d**." % (drawn, n, lvs_n, n),
        "- Assembled `pll_top` GDS committed under `layout/evidence/`: **%s**." % ("yes" if top_yes else "no"),
        "- KLayout pin for the committed deck logs (`layout/harness/env.py`): `%s`." % read_pin(root),
        END,
    ]
    return "\n".join(out) + "\n"


def splice(text, block):
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", text, re.S)
    if not m:
        sys.exit("FAIL: %s has no %s ... %s block" % (TARGET, BEGIN, END))
    return text[: m.start()] + block + text[m.end():]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=os.path.abspath(os.path.join(here, "..", "..")))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    target = os.path.join(args.root, TARGET)
    with open(target, encoding="utf-8") as fh:
        current = fh.read()
    wanted = splice(current, render(args.root))
    if wanted == current:
        print("OK: %s table matches the evidence tree" % TARGET)
        return 0
    if args.check:
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(True), wanted.splitlines(True),
                "committed/" + TARGET, "generated/" + TARGET,
            )
        )
        sys.stderr.write(
            "FAIL: %s is stale; run `python3 layout/lib/gen_layout_status_table.py`\n" % TARGET
        )
        return 1
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(wanted)
    print("rewrote %s" % TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
