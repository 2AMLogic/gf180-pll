#!/usr/bin/env python3
"""gf180-pll :: period-jitter :: S_id along the trajectory -- render results/ as markdown.

Every number quoted in this directory's README.md and in
`spec/decision-records/DR-031-*.md` comes out of here, so a reader can regenerate
the tables rather than trust that they were transcribed correctly:

    sim/period-jitter/sid-trajectory/summarize.py \
        > sim/period-jitter/sid-trajectory/results/SUMMARY.md

Reads only `results/*.json`; runs no simulation and needs no PDK.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import sid_deck  # noqa: E402
import sid_extract  # noqa: E402


def _load_run_module():
    """This directory's `run.py`, by PATH.

    A plain `import run` does not work here and the failure is quiet: `sid_deck`
    puts `../isf-bringup` on `sys.path` (it derives the trajectory deck from that
    directory's `isf_deck`), and `../isf-bringup/run.py` exists, so `import run`
    resolves to the ISF bring-up's runner instead of this one.
    """
    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "sid_trajectory_run", HERE / "run.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


#: Points in the order they are reported: the reference point first, then the two
#: extremes.  Taken from `run.py` rather than restated, so a point added there
#: appears here.
_run = _load_run_module()

POINT_ORDER = [_run.REFERENCE_POINT] + [
    p for p in _run.POINTS if p != _run.REFERENCE_POINT
]
DEVICES = list(sid_deck.RING_DEVICES)


def _load(results: Path, name: str):
    p = results / f"{name}.json"
    if not p.is_file():
        return None
    return json.loads(p.read_text())


def _fmt(x, spec=".3e"):
    if x is None:
        return "—"
    if isinstance(x, float) and x != x:
        return "NaN"
    return format(x, spec)


def _at(blocks, f, key):
    return next(b[key] for b in blocks if b["freq_Hz"] == f)


# ---------------------------------------------------------------------------
def render(results: Path) -> str:
    env = _load(results, "environment")
    if env is None:
        raise SystemExit(f"{results}/environment.json not found -- run run.py first")
    points = [p for p in POINT_ORDER if (results / f"sid_{p}.json").is_file()]
    L: list[str] = []
    a = L.append

    a("<!-- GENERATED by sim/period-jitter/sid-trajectory/summarize.py.")
    a("     Do not edit: regenerate with")
    a("       sim/period-jitter/sid-trajectory/summarize.py \\")
    a("           > sim/period-jitter/sid-trajectory/results/SUMMARY.md -->")
    a("")
    a("# S_id along the ring's own trajectory — results")
    a("")
    a("The ISF route's second and third ingredients for #520: each ring device's")
    a("channel-thermal and flicker generator PSD at the bias it actually occupies")
    a("at phase `x` of the oscillation, and the trajectory it is evaluated along.")
    a("**No jitter number is produced here** — see the directory README's *What")
    a("this does NOT establish* and `spec/decision-records/DR-031-*.md`.")
    a("")
    a(f"- ngspice: `{env['ngspice']}`")
    a(f"- PDK models: `{env['pdk_models']}`")
    a(f"- repo HEAD at run time: `{env['repo_head']}`")
    a(f"- `design/netlist/vco.spice` blob: `{env['vco_netlist_sha1']}`")
    a(f"- run (UTC): {env['utc']}  ·  quick mode: **{env['quick']}**")
    a("")

    # --- the PVT points -----------------------------------------------------
    a("## The three PVT points")
    a("")
    a("Each is a point of the 45-point matrix in")
    a("`sim/period-jitter/testbench/tb.json`, released at that point's own 150 MHz")
    a("control voltage from the same manifest. `f0` is measured on the trajectory")
    a("deck itself, from mid-supply crossings, the way")
    a("`../isf-bringup/`'s `period` stage measures it.")
    a("")
    a("| Point | MOS section | T (°C) | V_sup (V) | V_ctrl (V) | f0 (MHz) | transient (s) |")
    a("|---|---|---|---|---|---|---|")
    for p in points:
        traj = _load(results, f"trajectory_{p}")
        op = traj["operating_point"]
        a(f"| `{p}` | {op['mos_section']} | {op['temp_c']:g} | {op['vsup']:g} | "
          f"{op['vctrl']:g} | {traj['f0_Hz'] / 1e6:.4f} | "
          f"{traj['elapsed_s']:.1f} |")
    a("")

    # --- the extraction's own validity --------------------------------------
    a("## Is the extraction valid? (stage `checks`, and the per-phase residuals)")
    a("")
    a("Eight questions, each answered by measurement on every run rather than by an")
    a("argument. The first four are absolute checks — they compare against a")
    a("closed form or against a quantity that must not depend on a deck choice —")
    a("and any one of them failing invalidates every `S_id` in the same run. The")
    a("first is enforced in the runner rather than reported by it: a units anchor")
    a("outside 0.5 % aborts the whole point, because the deviation applies in the")
    a("same proportion to every `S_id` read off that run.")
    a("")
    a("| Check | What must hold | " + " | ".join(f"`{p}`" for p in points) + " |")
    a("|---|---|" + "---|" * len(points))

    rows: dict[str, list[str]] = {}
    for p in points:
        sid = _load(results, f"sid_{p}")
        chk = _load(results, f"checks_{p}")
        traj = _load(results, f"trajectory_{p}")
        anchors = [b["units_anchor"] for r in sid["rows"] for b in r["noise"]]
        rel = [abs(b[f"S_{g}_rel_diff"]) for r in sid["rows"] for b in r["noise"]
               for g in ("thermal", "flicker")]
        rep = sid["rows"]
        wv = max(max(abs(r["reproduction"][f"{q}_abs_diff"]) for q in ("vgs", "vds", "vbs"))
                 for r in rep)
        wi = max(max(abs(r["reproduction"][f"{q}_rel_diff"] or 0.0)
                     for q in ("id", "gm", "gds")) for r in rep)
        netspan = max(n["S_thermal_span_rel"] for n in chk["network"])
        white = max(f["thermal_whiteness"]["span_rel"] for f in chk["frequency"])
        alphas = [f["flicker_fit"]["alpha"] for f in chk["frequency"]]
        aresid = max(f["flicker_fit"]["max_abs_resid_dex"] for f in chk["frequency"])
        gn = [r["physics_bracket"]["g_n_over_largest_limit"] for r in sid["rows"]]
        rows.setdefault("anchor", []).append(
            f"{min(anchors):.7f}–{max(anchors):.7f}")
        rows.setdefault("norm", []).append(f"≤ {max(rel):.1e}")
        rows.setdefault("net", []).append(f"≤ {netspan:.2e}")
        rows.setdefault("repro", []).append(
            f"≤ {wv * 1e6:.1f} µV, ≤ {wi:.1e} rel")
        rows.setdefault("white", []).append(f"{white:.1e}")
        rows.setdefault("alpha", []).append(
            f"{min(alphas):.6f}–{max(alphas):.6f}, ≤ {aresid:.1e} dex")
        rows.setdefault("gn", []).append(f"{min(gn):.2f}–{max(gn):.2f}")
        rows.setdefault("snap", []).append(
            f"{traj['sid_grid_snap_max_phase_error_cycles']:.1e}")

    a("| Units anchor | the sense resistor's own thermal noise, measured / "
      "`sqrt(4kTR·bw)·Z_m/R`, must be 1 | " + " | ".join(rows["anchor"]) + " |")
    a("| Two normalisations | `(onoise/Z_m)²` vs ngspice's own `inoise²`, "
      "relative difference | " + " | ".join(rows["norm"]) + " |")
    a("| Network independence | `S_id` must not depend on the sense resistance; "
      "swept over 10⁷ (1 mΩ → 10 kΩ) | " + " | ".join(rows["net"]) + " |")
    a("| Bias reproduction | the standalone device must reproduce the in-situ "
      "`V_gs/V_ds/V_bs` and `I_d/g_m/g_ds` | " + " | ".join(rows["repro"]) + " |")
    a("| Thermal whiteness | channel-thermal density's spread over 1 kHz–300 MHz "
      "| " + " | ".join(rows["white"]) + " |")
    a("| Flicker exponent | fitted `α` in `S ∝ f^-α`, and the fit's worst residual "
      "| " + " | ".join(rows["alpha"]) + " |")
    a("| Physics bracket | `g_n = S_id/4kT` over `max(g_m, g_ds, I_d/2V_T)`; "
      "order unity or below | " + " | ".join(rows["gn"]) + " |")
    a("| Phase snap | how far the `S_id` grid's solved timepoints sit from the "
      "requested phases | " + " | ".join(rows["snap"]) + " |")
    a("")
    a("The measured `rd + rs` per device class, recovered from the noise deck's own")
    a("operating point at each device's peak-|I_d| phase (Ω):")
    a("")
    a("| Point | " + " | ".join(f"`{d}`" for d in DEVICES) + " |")
    a("|---|" + "---|" * len(DEVICES))
    for p in points:
        sid = _load(results, f"sid_{p}")
        a(f"| `{p}` | " + " | ".join(
            f"{sid['series_resistance'][d]['r_series_ohm']:.4f}" for d in DEVICES
        ) + " |")
    a("")

    # --- the two bias-method choices ----------------------------------------
    a("## Two deck choices, measured rather than argued (stage `checks`)")
    a("")
    a("Both are decisions the deck builder and the reduction make, and both are the")
    a("kind normally defended with an argument. Each is defended here with the")
    a("residual it leaves, at four phases of every device class: the peak-, median-")
    a("and minimum-`|I_d|` phases and the phase where `I_d` moves **fastest**.")
    a("")
    a("### The bias offsets are a Newton step on an observed residual, not `I_d·R`")
    a("")
    a("`V_gs`/`V_ds`/`V_bs` as ngspice reports them are measured across the channel,")
    a("inside the device's own `rd`/`rs` and the deck's sense resistor, so the ideal")
    a("sources have to be offset. The closed form `I_d·(rd + rs + rsense)` has no")
    a("fixed **sign**: BSIM4 swaps source and drain for `V_ds < 0`, so the reported")
    a("`I_d`'s sign stops following `V_ds` at the phases where a ring device's `V_ds`")
    a("crosses zero, and the two p-type devices add a polarity flip on top. Both")
    a("signs are run. Worst relative `I_d` residual per method, over all phases and")
    a("device classes of each corner:")
    a("")
    a("| Point | Newton step | `+I_d·R` | `−I_d·R` | worst point for the wrong sign |")
    a("|---|---|---|---|---|")
    for p in points:
        chk = _load(results, f"checks_{p}")
        bc = chk.get("bias_correction") or []
        if not bc:
            continue

        def _w(rows, get):
            return max(abs(get(r) or 0.0) for r in rows)

        newt = _w(bc, lambda r: r["newton_reproduction"]["id_rel_diff"])
        plus = _w(bc, lambda r: r["IdR_reproduction"]["plus_IdR"]["id_rel_diff"])
        minus = _w(bc, lambda r: r["IdR_reproduction"]["minus_IdR"]["id_rel_diff"])
        worst = max(bc, key=lambda r: max(
            abs(r["IdR_reproduction"][k]["id_rel_diff"] or 0.0)
            for k in ("plus_IdR", "minus_IdR")))
        a(f"| `{p}` | ≤ {newt:.1e} | ≤ {plus:.1e} | ≤ {minus:.1e} | "
          f"`{worst['instance']}` at `{worst['label']}`, "
          f"V_ds = {worst['vds_insitu'] * 1e3:+.2f} mV |")
    a("")
    a("Which sign is the better one **changes with the device and with the phase** —")
    a("at the reference corner `−I_d·R` wins on `XMPH`'s deep-triode phase and loses")
    a("by 3200× on `XMN`'s — which is the whole argument for a sign-agnostic step.")
    a("")
    a("### The `S_id` grid snaps to solved timepoints rather than interpolating")
    a("")
    a("Interpolating the six operating-point columns independently yields a row whose")
    a("`I_d` is not the `I_d` of its own bias triple. `rows differ` is how far apart")
    a("the two rows' `I_d` are; the two `reproduction` columns are each row's own")
    a("internal inconsistency, as the noise deck's operating point sees it.")
    a("")
    a("| Point | phase class | rows differ (rel `I_d`) | snapped row reproduces | "
      "interpolated row reproduces |")
    a("|---|---|---|---|---|")
    for p in points:
        chk = _load(results, f"checks_{p}")
        sv = chk.get("snap_vs_interp") or []
        labels = []
        for r in sv:
            if r["label"] not in labels:
                labels.append(r["label"])
        for lbl in labels:
            rows = [r for r in sv if r["label"] == lbl]
            a(f"| `{p}` | `{lbl}` | "
              f"≤ {max(abs(r['id_rel_diff_between_rows'] or 0.0) for r in rows):.1e} | "
              f"≤ {max(abs(r['snapped_reproduction']['id_rel_diff'] or 0.0) for r in rows):.1e} | "
              f"≤ {max(abs(r['interpolated_reproduction']['id_rel_diff'] or 0.0) for r in rows):.1e} |")
    a("")
    a("The snapped row's residual is ~1e-6 everywhere. The interpolated row's is")
    a("indistinguishable from it at the reference corner's three obvious phases —")
    a("over one 2 ps stored step the bias barely moves, so linear interpolation error")
    a("is second order there — and degrades by up to two and a half orders at the")
    a("**steepest** phase, at every corner. Adding that fourth phase is what made the")
    a("choice measurable: a three-phase check at the reference corner finds nothing")
    a("and would have licensed the conclusion that snapping is unnecessary.")
    a("")

    # --- are the five stages one trajectory? --------------------------------
    a("## Are the five ring stages one trajectory, shifted? (stage `trajectory`)")
    a("")
    a("A jitter sum that measures one stage and multiplies by five assumes they")
    a("are. The residual is quoted at the shift the topology predicts — "
      f"**{sid_extract.STAGE_SHIFT_CYCLES}** of a cycle per stage for an")
    a("inverting ring of five, i.e. `1/(2N) + 1/2`, **not** `1/N` — and the")
    a("best-fit shift is scanned rather than assumed, so that a residual at the")
    a("predicted shift is a statement about the stages and not about the")
    a("prediction. `Δ` is best-fit minus predicted, in cycles.")
    a("")
    a("| Point | quantity | worst \\|Δ\\| (cycles) | scan resolution | "
      "worst peak residual / p-p | worst RMS residual / p-p |")
    a("|---|---|---|---|---|---|")
    for p in points:
        traj = _load(results, f"trajectory_{p}")
        for param in ("vgs", "id"):
            blocks = [s for s in traj["stage_symmetry"] if s["param"] == param]
            # Stage 1 against itself is the identity and carries no information.
            st = [x for b in blocks for x in b["stages"] if x["stage"] != 1]
            # The current sources' gate sits on the SHARED bias net, so their
            # `vgs` has no stage shift at all -- reported separately below.
            shifted = [x for b in blocks for x in b["stages"]
                       if x["stage"] != 1 and not (
                           param == "vgs" and b["instance"] in ("XMPH", "XMNT"))]
            if not shifted:
                shifted = st
            a(f"| `{p}` | `{param}` | "
              f"{max(abs(x['best_fit_shift_minus_predicted_cycles']) for x in shifted):.4f} | "
              f"{st[0]['shift_scan_resolution_cycles']:.4f} | "
              f"{max(x['best_fit_peak_residual_frac_of_ptp'] for x in st):.3f} | "
              f"{max(x['best_fit_rms_residual_frac_of_ptp'] for x in st):.3f} |")
    a("")
    a("The two current-source devices' `V_gs` is the exception that confirms the")
    a("reading: their gate is the SHARED bias net `VBP`/`VBN`, so all five stages")
    a("see the same gate ripple with **no** stage shift, and the scan finds its")
    a("best fit at shift 0 rather than at 0.6. Their `V_ds` does swing with the")
    a("ring, and their `I_d` carries the 0.6 shift like everything else.")
    a("")
    a("| Point | device | `V_gs` p-p (V) | best-fit shift | residual at it / p-p |")
    a("|---|---|---|---|---|")
    for p in points:
        traj = _load(results, f"trajectory_{p}")
        for inst in ("XMPH", "XMNT"):
            b = next(s for s in traj["stage_symmetry"]
                     if s["param"] == "vgs" and s["instance"] == inst)
            st = [x for x in b["stages"] if x["stage"] != 1]
            a(f"| `{p}` | `{inst}` | {b['stage1_ptp']:.4g} | "
              f"{', '.join(f'{x['best_fit_shift_cycles']:.3f}' for x in st)} | "
              f"≤ {max(x['best_fit_peak_residual_frac_of_ptp'] for x in st):.4f} |")
    a("")

    # --- the cyclostationary span -------------------------------------------
    f_tab = _load(results, f"sid_{points[0]}")["f_tabulate_Hz"]
    a("## What the stationary approximation costs (stage `cost`)")
    a("")
    a(f"Densities at **{f_tab / 1e6:g} MHz**. `span` is `10·log10(max/min)` over the")
    a("sampled phases and is dominated by the phases where the device is OFF, so it")
    a("is a statement about the size of the cyclostationary variation and **not**")
    a("about the error any usable single-bias choice makes. The three convention")
    a("columns are that error: each is one single-bias `S_id` over the *unweighted*")
    a("cycle average, in dB. Positive means the convention over-states the average.")
    a("")
    for gen in ("thermal", "flicker"):
        a(f"### Channel-{gen} generator")
        a("")
        a("| Point | device | span (dB) | ⟨S⟩ (A²/Hz) | at peak \\|I_d\\| (dB) | "
          "at min \\|I_d\\| (dB) | at mean V_gs (dB) |")
        a("|---|---|---|---|---|---|---|")
        for p in points:
            cost = _load(results, f"cost_{p}")
            for d in DEVICES:
                g = cost["devices"][d][gen]
                c = g["conventions"]
                a(f"| `{p}` | `{d}` | {g['span_dB']:.2f} | "
                  f"{g['cycle_average']:.3e} | "
                  f"{c['at_peak_Id']['error_dB']:+.2f} | "
                  f"{c['at_min_Id']['error_dB']:+.2f} | "
                  f"{c['at_nearest_phase_to_mean_Vgs']['error_dB']:+.2f} |")
        a("")

    # --- the weighted cost --------------------------------------------------
    w = _load(results, f"weighted_{_run.REFERENCE_POINT}")
    if w is not None:
        a("## What it costs against the weighted average the integral contains "
          "(stage `weighted`)")
        a("")
        a("The jitter sum is `var(ΔT) = (1/ω0²)·(½)·∫ h_gen(t)² S_i(t) dt`, so the")
        a("number a stationary `S_id` has to get right is not `⟨S⟩` but")
        a("`S_eff = Σ h²S / Σ h²`: substituting a constant `S₀` makes the integral")
        a("wrong by exactly `S₀ / S_eff`. `h` is the committed table from")
        a("`../isf-bringup/`, so this stage exists only at the one PVT point where")
        a("that table was measured.")
        a("")
        a(f"- ISF `h` period {w['isf_period_s'] * 1e9:.6f} ns against this")
        a(f"  directory's trajectory {w['trajectory_period_s'] * 1e9:.6f} ns — "
          f"{w['period_rel_diff']:+.2e} relative, i.e. the two ingredients really")
        a("  are on one phase axis.")
        a("- `part` is `(Σh²)²/(n·Σh⁴)`: 1.0 if every sampled phase carries equal")
        a("  weight, `1/n` if one phase carries all of it. `n_eff = n·part` is the")
        a("  effective number of phases setting `S_eff`, and it is the resolution")
        a("  limit on these figures.")
        a("- **`exact`** says whether the weight is the generator's own `h_gen` or a")
        a("  declared shape proxy. A channel generator sits between drain and")
        a("  source, so `h_gen = h(source) − h(drain)`. For the two current-source")
        a("  devices the source is an ideal rail (`VDD` is a voltage source, `VSS` is")
        a("  node 0), so `h(source) = 0` identically and `|h_gen| = |h(drain)|` with")
        a("  no subtraction. For the two switching devices both terminals are ring")
        a("  nodes; DR-030 measured that residue at 1.54 % of the larger term and")
        a("  rejected building it by subtraction, so `h(Y)` stands in as a weight")
        a("  SHAPE only and no contribution is claimed from those rows.")
        a("")
        for gen in ("thermal", "flicker"):
            a(f"### Channel-{gen} generator, `h²`-weighted")
            a("")
            a("| device | weight | exact | n | n_eff | S_eff (A²/Hz) | "
              "S_eff/⟨S⟩ (dB) | at peak \\|I_d\\| (dB) | at min \\|I_d\\| (dB) | "
              "at mean V_gs (dB) |")
            a("|---|---|---|---|---|---|---|---|---|---|")
            for d in DEVICES:
                dv = w["devices"][d]
                g = dv[gen]
                c = g["conventions"]
                a(f"| `{d}` | `h({dv['weight_node']})` | "
                  f"{'yes' if dv['weight_is_exact_h_gen'] else 'shape proxy'} | "
                  f"{g['n_phases']} | "
                  f"{g['n_phases'] * g['h2_participation']:.1f} | "
                  f"{g['S_eff_A2_per_Hz']:.3e} | "
                  f"{g['weighted_over_unweighted_dB']:+.2f} | "
                  f"{c['at_peak_Id']['error_dB']:+.2f} | "
                  f"{c['at_min_Id']['error_dB']:+.2f} | "
                  f"{c['at_nearest_phase_to_mean_Vgs']['error_dB']:+.2f} |")
            a("")

    # --- the tables themselves ---------------------------------------------
    a("## The ingredient itself")
    a("")
    a(f"`S_id` at **{f_tab / 1e6:g} MHz** per device per sampled phase, and the bias")
    a("it was measured at. This is the table an assembled pipeline consumes; the")
    a("committed `results/sid_<point>.json` additionally holds every frequency, both")
    a("normalisations, the reproduction residuals and the physics bracket per row,")
    a("and `results/trajectory_<point>.json` holds the 4×-finer trajectory.")
    a("")
    for p in points:
        sid = _load(results, f"sid_{p}")
        a(f"### `{p}`")
        a("")
        a("| phase (cycles) | device | V_gs (V) | V_ds (V) | V_bs (V) | I_d (A) | "
          "S_thermal (A²/Hz) | S_flicker (A²/Hz) |")
        a("|---|---|---|---|---|---|---|---|")
        for r in sorted(sid["rows"], key=lambda r: (r["phase_cycles"],
                                                    DEVICES.index(r["instance"]))):
            b = r["bias_insitu"]
            a(f"| {r['phase_cycles']:.4f} | `{r['instance']}` | "
              f"{b['vgs']:+.4f} | {b['vds']:+.4f} | {b['vbs']:+.4f} | "
              f"{b['id']:+.4e} | "
              f"{_at(r['noise'], f_tab, 'S_thermal_A2_per_Hz'):.4e} | "
              f"{_at(r['noise'], f_tab, 'S_flicker_A2_per_Hz'):.4e} |")
        a("")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default=str(HERE / "results"))
    args = ap.parse_args(argv)
    print(render(Path(args.results)), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
